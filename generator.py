if __name__ == "__main__":

    from retriever import RuleRetriever
    from reranker import RuleReranker

    print("=" * 70)
    print("CHARGEBACK EVIDENCE GENERATOR TEST")
    print("=" * 70)

    # ---------------------------------------------------------------
    # Initialize components
    # ---------------------------------------------------------------

    print("\nLoading retriever...")
    retriever = RuleRetriever()

    print("Loading reranker...")
    reranker = RuleReranker()

    print("Loading LLM generator...")
    generator = EvidenceGenerator()

    # ---------------------------------------------------------------
    # Example case
    # ---------------------------------------------------------------

    example_facts = {
        "delivery_confirmed": False,
        "otp_auth_confirmed": True,
        "shipping_billing_match": True,
        "prior_complaint_on_file": False,
        "amount": 2400,
        "days_to_dispute": 12,
    }

    reason_code = "item_not_received"

    # ---------------------------------------------------------------
    # Retrieval
    # ---------------------------------------------------------------

    print("\nRunning retrieval...")

    retrieval = retriever.retrieve(
        reason_code,
        example_facts,
    )

    print(
        f"Retrieved {len(retrieval['results'])} rule chunks."
    )

    # ---------------------------------------------------------------
    # Reranking
    # ---------------------------------------------------------------

    print("Running reranker...")

    top3 = reranker.rerank(
        retrieval["query"],
        retrieval["results"],
        top_n=3,
    )

    print(
        f"Reranked to {len(top3)} chunks."
    )

    print("\nTop retrieved rules:")

    for chunk in top3:
        print(
            f"  - {chunk['chunk_id']} "
            f"(score={chunk.get('rerank_score', 0):.4f})"
        )

    # ---------------------------------------------------------------
    # LLM generation
    # ---------------------------------------------------------------

    print("\nGenerating evidence response...")

    result = generator.generate(
        dispute_id="DSP-DEMO-001",
        reason_code=reason_code,
        case_facts=example_facts,
        retrieved_chunks=top3,
        win_probability=0.14,
        decision="MANUAL_REVIEW",
    )

    # ---------------------------------------------------------------
    # Output
    # ---------------------------------------------------------------

    print("\n" + "=" * 70)
    print("RESULT")
    print("=" * 70)

    print(f"\nStatus: {result['status']}")
    print(f"Decision: {result['decision']}")
    print(f"Win probability: {result['win_probability']:.3f}")

    if result["status"] == "DRAFTED":

        print(f"Model: {result['model']}")

        print(
            "\nRetrieved chunk IDs:",
            ", ".join(result["retrieved_chunk_ids"])
        )

        print("\n" + "-" * 70)
        print("GENERATED EVIDENCE RESPONSE")
        print("-" * 70)

        print(result["draft"])

    else:

        print("\nNote:")
        print(result["note"])

    print("\n" + "=" * 70)